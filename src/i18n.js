/** Sunucu tarafı metni: t('tr', 'quotaReset', { time }) */
export function t(ui, key, vars = {}) {
  const value = STRINGS[ui]?.[key] ?? STRINGS[DEFAULT_UI][key];
  const fill = (s) => s.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
  return Array.isArray(value) ? value.map(fill) : fill(value);
}
